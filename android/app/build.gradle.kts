import com.android.build.api.variant.AndroidComponentsExtension

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
}

val ndkPinned = "30.0.16248370"

// One version for the whole project: the workspace's, from Cargo.toml.
val glftVersion = rootDir.resolve("../Cargo.toml").readLines()
    .first { it.startsWith("version = ") }.substringAfter('"').substringBefore('"')
val glftVersionCode = glftVersion.split('.').map(String::toInt).let { (a, b, c) -> a * 10000 + b * 100 + c }

android {
    namespace = "io.github.contentist.glft"
    compileSdk = 37
    ndkVersion = ndkPinned

    defaultConfig {
        applicationId = "io.github.contentist.glft"
        minSdk = 34
        targetSdk = 37
        versionCode = glftVersionCode
        versionName = glftVersion
        ndk { abiFilters += "arm64-v8a" }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
        }
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging { jniLibs { useLegacyPackaging = false } }
}

// The Rust core: built with cargo-ndk, Kotlin bindings generated by UniFFI.
val repoRoot: File = rootProject.projectDir.parentFile
val androidComponents = extensions.getByType(AndroidComponentsExtension::class.java)
val ndkDir = androidComponents.sdkComponents.ndkDirectory

abstract class CargoNdk : Exec() {
    @get:OutputDirectory abstract val outDir: DirectoryProperty
}

abstract class UniffiBindgen : Exec() {
    @get:OutputDirectory abstract val outDir: DirectoryProperty
}

val cargoNdk = tasks.register<CargoNdk>("cargoNdk") {
    outDir.set(layout.buildDirectory.dir("rust/jniLibs"))
    workingDir = repoRoot
    // Cargo decides what is stale; Gradle always asks it.
    outputs.upToDateWhen { false }
    doFirst {
        environment("ANDROID_NDK_HOME", ndkDir.get().asFile.path)
        commandLine(
            "cargo", "ndk", "-t", "arm64-v8a", "--platform", "34",
            "-o", outDir.get().asFile.path,
            "build", "-p", "glft-ffi", "--release", "--locked",
        )
    }
}

val uniffiBindgen = tasks.register<UniffiBindgen>("uniffiBindgen") {
    dependsOn(cargoNdk)
    outDir.set(layout.buildDirectory.dir("generated/uniffi"))
    workingDir = repoRoot
    outputs.upToDateWhen { false }
    doFirst {
        commandLine(
            "cargo", "run", "--quiet", "--locked", "-p", "glft-ffi", "--features", "bindgen",
            "--bin", "uniffi-bindgen", "--",
            "generate", "--library", "target/aarch64-linux-android/release/libglft_ffi.so",
            "--language", "kotlin", "--no-format", "--out-dir", outDir.get().asFile.path,
        )
    }
}

androidComponents.onVariants { variant ->
    variant.sources.jniLibs?.addGeneratedSourceDirectory(cargoNdk, CargoNdk::outDir)
    variant.sources.kotlin?.addGeneratedSourceDirectory(uniffiBindgen, UniffiBindgen::outDir)
}

